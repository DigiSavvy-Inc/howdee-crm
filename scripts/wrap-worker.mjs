// #729: run by `npm run build` right after `vite build`. Wraps the Cloudflare adapter's Worker so
// the app has a `scheduled` handler (the built-in clock); see scripts/wrap-worker-lib.mjs.
//
//   node scripts/wrap-worker.mjs [dir]     dir defaults to .svelte-kit/cloudflare/worker
//
// #741: adapter-cloudflare 9 deploys unbundled (its generated wrangler.json has `no_bundle: true`),
// so src/lib/server/internal-tick.ts is transpiled to JS here and written next to the Worker. The
// file imports nothing but `cloudflare:workers` (a runtime built-in), so transpiling it on its own
// is enough.
import { existsSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import ts from 'typescript';

import { wrapWorker } from './wrap-worker-lib.mjs';
// The marker the deploy checks for (scripts/deploy-plan.mjs imports it from the lib, which has no
// node imports).
export { WRAPPER_MARKER } from './wrap-worker-lib.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TICK_TS = path.join(root, 'src/lib/server/internal-tick.ts');

/**
 * internal-tick.ts as an ES module. Throws on a syntax error, so the build fails.
 * @param {string} source
 */
export function transpileTick(source) {
	const out = ts.transpileModule(source, {
		fileName: 'internal-tick.ts',
		reportDiagnostics: true,
		compilerOptions: {
			module: ts.ModuleKind.ESNext,
			target: ts.ScriptTarget.ES2022,
			verbatimModuleSyntax: true,
			sourceMap: false
		}
	});
	const errors = (out.diagnostics ?? []).filter((d) => d.category === ts.DiagnosticCategory.Error);
	if (errors.length) {
		throw new Error(`wrap-worker: could not transpile ${path.relative(root, TICK_TS)}: ${errors.map((d) => ts.flattenDiagnosticMessageText(d.messageText, ' ')).join('; ')}`);
	}
	return `// @generated by scripts/wrap-worker.mjs from src/lib/server/internal-tick.ts (#741). Do not edit.\n${out.outputText}`;
}

function main() {
	const dir = path.resolve(root, process.argv[2] ?? '.svelte-kit/cloudflare/worker');
	const fs = {
		exists: (/** @type {string} */ p) => existsSync(p),
		read: (/** @type {string} */ p) => readFileSync(p, 'utf8'),
		write: (/** @type {string} */ p, /** @type {string} */ text) => writeFileSync(p, text),
		rename: (/** @type {string} */ from, /** @type {string} */ to) => renameSync(from, to)
	};
	try {
		const tickSource = transpileTick(readFileSync(TICK_TS, 'utf8'));
		const { wrapped } = wrapWorker(dir.split(path.sep).join('/'), fs, { tickSource });
		console.log(wrapped ? `wrap-worker: ${path.relative(root, dir)}/index.js now has the scheduled tick` : 'wrap-worker: already wrapped');
	} catch (e) {
		console.error(e instanceof Error ? e.message : String(e));
		process.exit(1);
	}
}

if (process.argv[1] != null && import.meta.url === pathToFileURL(process.argv[1]).href) main();
