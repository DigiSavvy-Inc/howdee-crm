/**
 * #729: the pure part of scripts/wrap-worker.mjs, run by `npm run build` after `vite build`.
 *
 * #741: @sveltejs/adapter-cloudflare 9 writes the Worker to `.svelte-kit/cloudflare/worker/`:
 * `index.js` (the entry, exports only `fetch`), `server.js` + `server/` (the app), and a generated
 * `wrangler.json` (`main: "index.js"`, `no_bundle: true`, static assets in `../client`). The
 * adapter also writes `.wrangler/deploy/config.json`, which points `wrangler deploy` (and `wrangler
 * dev`) at that generated config. Because the deploy is unbundled, everything the Worker imports
 * must already be JS in this folder.
 *
 * So this moves the adapter's `index.js` to `_app.js`, writes `internal-tick.js` (the caller passes
 * src/lib/server/internal-tick.ts transpiled to JS) and writes a new `index.js` that imports both
 * and exports `withClock(app)`: `fetch` unchanged, plus a `scheduled` handler that runs one
 * automation tick. Every build gets the handler; it only fires when the wrangler config has
 * `triggers.crons`.
 *
 * The folder is not the static assets directory any more (that is `../client`), so nothing here
 * can be served as a public file and no `.assetsignore` entry is needed.
 *
 * No node imports: the caller passes the file operations, so tests run it on a fake file map.
 */

/** First line of the generated wrapper; how a second run knows the folder is already wrapped. */
export const WRAPPER_MARKER = '// @generated by scripts/wrap-worker.mjs (#729)';
/** The adapter's Worker entry, named by `main` in its generated wrangler.json. */
export const WORKER_FILE = 'index.js';
export const APP_FILE = '_app.js';
export const TICK_FILE = 'internal-tick.js';
export const CONFIG_FILE = 'wrangler.json';

/** The wrapper's source. */
export function wrapperSource() {
	return [
		WRAPPER_MARKER,
		'// The SvelteKit adapter Worker (./_app.js, fetch only) plus a scheduled handler that runs one',
		'// automation tick (fires only with `triggers.crons` in the wrangler config). Do not edit.',
		`import app from './${APP_FILE}';`,
		`import { withClock } from './${TICK_FILE}';`,
		`export * from './${APP_FILE}';`,
		'export default withClock(app);',
		''
	].join('\n');
}

/**
 * @typedef {{
 *   exists(path: string): boolean,
 *   read(path: string): string,
 *   write(path: string, text: string): void,
 *   rename(from: string, to: string): void
 * }} WrapFs
 */

/**
 * Wrap the adapter output in `dir`. Idempotent: a folder already wrapped is left as it is (the
 * wrapper and `internal-tick.js` are still checked). Throws when there is no `index.js` (the adapter
 * didn't run or wrote somewhere else) or when the generated wrangler.json names another entry, so
 * the build fails loudly instead of deploying a Worker without its clock.
 * @param {string} dir the adapter's Worker folder (`.svelte-kit/cloudflare/worker`)
 * @param {WrapFs} fs
 * @param {{ tickSource: string }} opts tickSource = internal-tick.ts as JavaScript
 * @returns {{ wrapped: boolean, tickUpdated: boolean }} wrapped = this call moved the adapter file
 */
export function wrapWorker(dir, fs, opts) {
	const at = (/** @type {string} */ name) => `${dir.replace(/\/+$/, '')}/${name}`;
	const worker = at(WORKER_FILE);
	const app = at(APP_FILE);
	if (!fs.exists(worker)) {
		throw new Error(`wrap-worker: ${worker} not found. Run \`vite build\` first (the Cloudflare adapter writes its Worker there).`);
	}
	const config = at(CONFIG_FILE);
	if (fs.exists(config)) {
		/** @type {unknown} */
		let main;
		try {
			main = JSON.parse(fs.read(config)).main;
		} catch {
			throw new Error(`wrap-worker: ${config} is not valid JSON.`);
		}
		if (main !== WORKER_FILE) {
			throw new Error(`wrap-worker: ${config} has "main": ${JSON.stringify(main)}, expected "${WORKER_FILE}". The adapter's output layout changed; update scripts/wrap-worker-lib.mjs.`);
		}
	}
	if (!opts.tickSource.trim()) throw new Error('wrap-worker: the internal tick module is empty.');

	let wrapped = false;
	const current = fs.read(worker);
	if (current.startsWith(WRAPPER_MARKER)) {
		if (!fs.exists(app)) throw new Error(`wrap-worker: ${worker} is the wrapper but ${app} is missing. Run \`npm run build\` again.`);
	} else {
		fs.rename(worker, app); // replaces a stale _app.js
		wrapped = true;
	}
	const source = wrapperSource();
	if (wrapped || current !== source) fs.write(worker, source);

	const tick = at(TICK_FILE);
	const tickUpdated = !fs.exists(tick) || fs.read(tick) !== opts.tickSource;
	if (tickUpdated) fs.write(tick, opts.tickSource);
	return { wrapped, tickUpdated };
}
