/**
 * #729: the pure part of scripts/wrap-worker.mjs, run by `npm run build` after `vite build`.
 *
 * @sveltejs/adapter-cloudflare writes its Worker to wrangler's `main`
 * (`.svelte-kit/cloudflare/_worker.js`), deleting it first, and that Worker exports only `fetch`.
 * This moves it to `_app.js` in the same folder and writes a new `_worker.js` that imports it and
 * exports `withClock(app)` (src/lib/server/internal-tick.ts): `fetch` unchanged, plus a `scheduled`
 * handler that runs one automation tick. Every build gets the handler; it only fires when the
 * wrangler config has `triggers.crons`.
 *
 * The folder is also the static assets directory, so `_app.js` (server code) is added to the
 * adapter's `.assetsignore` and is never served as a public file.
 *
 * No node imports: the caller passes the file operations, so tests run it on a fake file map.
 */

/** First line of the generated wrapper; how a second run knows the folder is already wrapped. */
export const WRAPPER_MARKER = '// @generated by scripts/wrap-worker.mjs (#729)';
export const WORKER_FILE = '_worker.js';
export const APP_FILE = '_app.js';
export const ASSETS_IGNORE = '.assetsignore';

/**
 * The wrapper's source.
 * @param {string} tickModule import specifier of src/lib/server/internal-tick.ts, relative to the folder
 */
export function wrapperSource(tickModule) {
	return [
		WRAPPER_MARKER,
		'// The SvelteKit adapter Worker (./_app.js, fetch only) plus a scheduled handler that runs one',
		'// automation tick (fires only with `triggers.crons` in the wrangler config). Do not edit.',
		`import app from './${APP_FILE}';`,
		`import { withClock } from '${tickModule}';`,
		`export * from './${APP_FILE}';`,
		'export default withClock(app);',
		''
	].join('\n');
}

/**
 * `text` with `_app.js` on a line of its own (unchanged when already listed).
 * @param {string} text
 */
export function withAppIgnored(text) {
	const lines = text.split(/\r?\n/).map((l) => l.trim());
	if (lines.includes(APP_FILE) || lines.includes(`/${APP_FILE}`)) return text;
	return `${text}${text === '' || text.endsWith('\n') ? '' : '\n'}${APP_FILE}\n`;
}

/**
 * @typedef {{
 *   exists(path: string): boolean,
 *   read(path: string): string,
 *   write(path: string, text: string): void,
 *   rename(from: string, to: string): void
 * }} WrapFs
 */

/**
 * Wrap the adapter output in `dir`. Idempotent: a folder already wrapped is left as it is (the
 * wrapper and `.assetsignore` are still checked). Throws when there is no `_worker.js` (the
 * adapter didn't run or wrote somewhere else), so the build fails loudly.
 * @param {string} dir the adapter's output folder
 * @param {WrapFs} fs
 * @param {{ tickModule: string }} opts
 * @returns {{ wrapped: boolean, ignoreUpdated: boolean }} wrapped = this call moved the adapter file
 */
export function wrapWorker(dir, fs, opts) {
	const at = (/** @type {string} */ name) => `${dir.replace(/\/+$/, '')}/${name}`;
	const worker = at(WORKER_FILE);
	const app = at(APP_FILE);
	if (!fs.exists(worker)) {
		throw new Error(`wrap-worker: ${worker} not found. Run \`vite build\` first (the Cloudflare adapter writes it to wrangler's "main").`);
	}
	let wrapped = false;
	const current = fs.read(worker);
	if (current.startsWith(WRAPPER_MARKER)) {
		if (!fs.exists(app)) throw new Error(`wrap-worker: ${worker} is the wrapper but ${app} is missing. Run \`npm run build\` again.`);
	} else {
		fs.rename(worker, app); // replaces a stale _app.js
		wrapped = true;
	}
	const source = wrapperSource(opts.tickModule);
	if (wrapped || current !== source) fs.write(worker, source);

	const ignore = at(ASSETS_IGNORE);
	const before = fs.exists(ignore) ? fs.read(ignore) : '';
	const after = withAppIgnored(before);
	const ignoreUpdated = after !== before;
	if (ignoreUpdated) fs.write(ignore, after);
	return { wrapped, ignoreUpdated };
}
